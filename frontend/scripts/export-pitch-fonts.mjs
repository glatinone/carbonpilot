/**
 * Copies the typefaces the app already ships into the pitch deck's folder.
 *
 * The deck is a standalone HTML file: it has no build step and does not go through
 * next/font, so it cannot reference the app's font URLs (they are content-hashed and
 * live under `_next/`). Left alone it would fall back to Georgia and system-ui and
 * read as a different product. This copies the exact subset files the app uses and
 * rewrites the @font-face rules to point at them locally.
 *
 * Run after `npm run build` and after any change to the fonts in `app/layout.tsx`:
 *
 *     node scripts/export-pitch-fonts.mjs
 *
 * Every subset is kept, not just basic latin: the deck prints "tCO₂e" (U+2082) and
 * "→" (U+2192), and those glyphs live outside the latin range. Dropping them would
 * silently swap in a system font for exactly the characters that carry the units.
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const CSS_DIR = "out/_next/static/css";
const MEDIA_DIR = "out/_next/static/media";
const DEST = "public/pitch";
const FONT_DEST = join(DEST, "fonts");

// The three families the design system is built on, plus the fallback family
// next/font generates for each, which carries the metric-override rules.
const WANTED = ["Source Serif 4", "Inter", "IBM Plex Mono"];

if (!existsSync(CSS_DIR)) {
  console.error(`No build output at ${CSS_DIR}. Run \`npm run build\` first.`);
  process.exit(1);
}

const css = readdirSync(CSS_DIR)
  .filter((name) => name.endsWith(".css"))
  .map((name) => readFileSync(join(CSS_DIR, name), "utf8"))
  .join("\n");

const blocks = css.match(/@font-face\s*\{[^}]*\}/g) ?? [];
mkdirSync(FONT_DEST, { recursive: true });

const kept = [];
const copied = new Set();

for (const block of blocks) {
  const family = block.match(/font-family:\s*([^;]+)/)?.[1]?.trim().replace(/^["']|["']$/g, "");
  if (!family) continue;
  if (!WANTED.some((wanted) => family === wanted || family === `${wanted} Fallback`)) continue;

  const source = block.match(/url\(([^)]+)\)/)?.[1];
  if (!source) continue;

  const file = basename(source.replace(/["']/g, ""));
  const from = join(MEDIA_DIR, file);
  if (!existsSync(from)) continue;

  if (!copied.has(file)) {
    copyFileSync(from, join(FONT_DEST, file));
    copied.add(file);
  }
  kept.push(block.replace(/url\([^)]+\)/, `url(fonts/${file})`));
}

if (kept.length === 0) {
  console.error("No matching @font-face rules found — did the font imports change?");
  process.exit(1);
}

const header = [
  "/*",
  " * Generated by scripts/export-pitch-fonts.mjs — do not edit by hand.",
  " * The pitch deck's copy of the app's own typefaces, so the two render alike",
  " * without a build step and without a network request for a font.",
  " */",
  "",
].join("\n");

writeFileSync(join(DEST, "fonts.css"), header + kept.join("\n\n") + "\n", "utf8");

const families = [...new Set(kept.map((b) => b.match(/font-family:\s*([^;]+)/)[1].trim()))];
console.log(`Wrote ${join(DEST, "fonts.css")}`);
console.log(`  rules   : ${kept.length}`);
console.log(`  files   : ${copied.size}`);
console.log(`  families: ${families.length}`);
